def _ogtitle(t):
    """OGP画像の題。長い語は、真ん中あたりで1回だけ折ります"""
    t = t.split('（')[0] + 'とは？'
    if len(t) <= 11:
        return t
    h = len(t) // 2
    return t[:h] + '<br>' + t[h:]


def dump_og():
    """OGP画像の中身を書き出す（ogspec.py が読みます）

    1ページ1枚にします。同じ絵を使い回すと、SNSに貼ったときに
    どのページも同じ見た目になり、checkgen.py も止めます。
    """
    import json
    P = [dict(f='og-p-words.png', eyebrow='新規事業の言葉',
              title='担当になった日に、<br>引くための%d語。' % len(W),
              sub='のれん、カーブアウト、持分法、TOB、社内公募制度。')]
    for x in W:
        P.append(dict(f='og-p-words-%s.png' % x['slug'],
                      eyebrow='新規事業の言葉 ／ %s' % x['cat'],
                      title=_ogtitle(x['term']),
                      sub=x['short'][:46]))
    json.dump(P, io.open('/tmp/words_og.json', 'w', encoding='utf-8'), ensure_ascii=False)


