ITEMS = newsdata.build()


def cases(x, n=5):
    """この言葉が実際に出てくる記録を最大n件

    keys は前にあるものほど、その言葉そのものを指しています。
    たとえば社内公募制度なら、'アクセラレー' に当たった記録より
    'SSAP' に当たった記録のほうが、探している人の知りたいものです。
    だから当たったキーの順を先に見て、そのあと新しい順にします。
    """
    hit = []
    for it in ITEMS:
        blob = (it['title'] + ' ' + it['note'] + ' ' + (it.get('srclabel') or ''))
        for rank, k in enumerate(x['keys']):
            if k in blob:
                hit.append((rank, it['i'], it))
                break
    hit.sort(key=lambda t: (t[0], t[1]))
    return [t[2] for t in hit[:n]]


def case_list(x):
    cs = cases(x)
    if not cs:
        return ''
    li = ''.join(
        '<li><a href="/news/%s/">%s</a>　<span class="mt">%s・%s</span></li>'
        % (it['slug'], esc(it['co'] + '　' + it['title']), esc(it['ym']), esc(it['co']))
        for it in cs)
    return ('<h2>この言葉が実際に出てくる記録</h2>'
            '<p>NEWFORが公開情報から拾った%d件の中から、この言葉が出てくるものを新しい順に並べました。'
            '意味だけ読むより、実際に使われている場面を見たほうが早く入ります。</p>'
            '<ul class="cs">%s</ul>' % (len(ITEMS), li))


def see_also(x):
    v = x.get('see') or []
    if not v:
        return ''
    li = ''.join('<li><a href="%s">%s</a></li>' % (u, esc(t)) for u, t in v)
    return '<h2>この言葉が出てくる記事</h2><ul class="cs">%s</ul>' % li


def related(x):
    same = [y for y in W if y['cat'] == x['cat'] and y['slug'] != x['slug']]
    if not same:
        return ''
    li = ''.join('<li><a href="/words/%s/">%s</a>　%s</li>'
                 % (y['slug'], esc(y['term']), esc(y['short'])) for y in same)
    return '<h2>同じ分類の言葉</h2><ul class="cs">%s</ul>' % li


